# Each explored-area piece's hole: its overlay art's alpha turned inside out (opaque where the piece
# paints nothing), for the hide layer (Stitch.lua, Shade.Hide.Build): an unexplored piece's blank art is
# drawn through the holes of the explored pieces over it, so it shows only where none of them paints,
# soft-edged, as the game's map shows its blank art round the pieces it draws.
#
#   python -P tools/map-data/reveal_holes.py <World of Warcraft folder> [product] [client]
#   product: the install's product in .build.info (WoW Forever's: wowf); client: Forever
#
# Reads the pieces from OpenMap/Data/<client>/Reveal.lua (their overlay tiles from the game's own
# install, tools/casc) and writes OpenMap/Media/Textures/<client>/MapRevealHole/<UiMapArtID>/<w>_<h>_<x>_<y>.tga:
# the piece at about a quarter of its size, in a power of two each way less a border of one opaque
# texel, so the mask, clamped, is opaque all round the piece (Stitch.lua lays it one texel past the piece).
# And OpenMap/Data/<client>/RevealBounds.lua: where in each of a piece's tiles its art paints, so the
# hide layer draws a piece's blank art, and uses its hole, only there (the rest is transparent anyway,
# and a tile's whole square drawn through masks was most of the map's cost with it on).
import io, math, os, re, sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "casc"))
from casc import Casc  # noqa: E402

TILE = 256      # an overlay's tiles
PAINTS = 2      # alpha above this: the piece paints there
SCALE = 4       # the hole's texels a piece's px
MIN = 16        # the smallest side


def pow2(n):
    p = MIN
    while p < n:
        p *= 2
    return p


def pieces(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\s*\[(\d+)\] = \{(.*)\},?\s*$", line)
        if m:
            out[int(m.group(1))] = re.findall(r'\["(\d+:\d+:\d+:\d+)"\] = "([\d, ]+)"', m.group(2))
    return out


def alpha(casc, key, ids):
    w, h, _, _ = (int(v) for v in key.split(":"))
    ids = [int(v) for v in ids.split(",")]
    cols, rows = math.ceil(w / TILE), math.ceil(h / TILE)
    a = Image.new("L", (w, h), 0)
    for j in range(rows):
        for k in range(cols):
            i = j * cols + k
            if i >= len(ids) or not ids[i]:
                continue
            a.paste(Image.open(io.BytesIO(casc.read(ids[i]))).convert("RGBA").getchannel("A"), (k * TILE, j * TILE))
    return a


def hole(a):
    w, h = a.size
    tw, th = pow2(math.ceil(w / SCALE)), pow2(math.ceil(h / SCALE))
    inner = a.resize((tw - 2, th - 2), Image.BOX)
    out = Image.new("L", (tw, th), 0)
    out.paste(inner, (1, 1))
    inv = Image.fromarray(255 - np.asarray(out, dtype=np.uint8))
    return Image.merge("RGBA", (Image.new("L", (tw, th), 255),) * 3 + (inv,))


def bounds(a):
    """each tile's box where the piece paints (x0, y0, x1, y1, its own px), row-major; None: nowhere"""
    w, h = a.size
    px = np.asarray(a)
    out = []
    for j in range(math.ceil(h / TILE)):
        for k in range(math.ceil(w / TILE)):
            t = px[j * TILE:(j + 1) * TILE, k * TILE:(k + 1) * TILE] > PAINTS
            ys, xs = np.nonzero(t)
            out.append(None if len(xs) == 0 else (k * TILE + int(xs.min()), j * TILE + int(ys.min()),
                                                  k * TILE + int(xs.max()) + 1, j * TILE + int(ys.max()) + 1))
    return out


def main():
    folder = sys.argv[1]
    product = sys.argv[2] if len(sys.argv) > 2 else "wowf"
    client = sys.argv[3] if len(sys.argv) > 3 else "Forever"
    root = os.path.join(HERE, "..", "..", "OpenMap")
    out = os.path.join(root, "Media", "Textures", client, "MapRevealHole")
    casc = Casc(folder, product)
    n = 0
    lines = [
        "-- Where each explored-area piece's art paints: [UiMapArtID] = { [\"w:h:x:y\"] = \"x0 y0 x1 y1, ...\" }, a",
        "-- box per tile (row-major, the piece's own px; \"-\": a tile that paints nothing).",
        "-- Generated by tools/map-data/reveal_holes.py from the game's overlay tiles; regenerate rather than edit.",
        "",
        "local _, ns = ...",
        "",
        "ns.MapRevealBounds = {",
    ]
    for art, items in sorted(pieces(os.path.join(root, "Data", client, "Reveal.lua")).items()):
        os.makedirs(os.path.join(out, str(art)), exist_ok=True)
        boxes = []
        for key, ids in sorted(items):
            a = alpha(casc, key, ids)
            hole(a).save(os.path.join(out, str(art), key.replace(":", "_") + ".tga"))
            boxes.append('["%s"] = "%s"' % (key, ", ".join("-" if b is None else "%d %d %d %d" % b for b in bounds(a))))
            n += 1
        lines.append("\t[%d] = {%s}," % (art, ", ".join(boxes)))
    lines.append("}")
    open(os.path.join(root, "Data", client, "RevealBounds.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %d holes and RevealBounds.lua" % n)


if __name__ == "__main__":
    main()
